#!/usr/bin/env python3
"""lcdtest.py - turns advent-lcd's log (host_lcd.c: "<display>\\t<key>"
per key the program waited for) into a pc1500runner script: wait until
the emulated display shows the same, then press the same key.

The runner reads the display with the ROM's font as learned from BASIC
PRINTs (and the C library's own ' [ ]), and some characters don't read
back, so each display is checked by its longest run of letters, digits
and a little punctuation ('_' for a space, as the runner's u: wants).

Usage: lcdtest.py log seed > script
"""

import re
import sys

PAUSE = int(sys.argv[3]) if len(sys.argv) > 3 else 300
SAFE = re.compile(r"[A-Za-z0-9 .,!?>'-]+")


def fragment(display):
    runs = SAFE.findall(display)
    best = max(runs, key=len) if runs else ""
    best = best.strip() or best
    return best.replace(" ", "_")


seed = int(sys.argv[2])
print("# generated by test/lcdtest.py")
print("w:1500 k:ENT w:1500")                      # the title; then the seed
print("p:_ranState:=%08X" % seed)
prev = None
for line in open(sys.argv[1]):
    display, key = line.rstrip("\n").split("\t")
    if key == "END":
        frag = fragment(display)
        print(f"u:{frag}:60000" if frag else "w:2000")
        break
    frag = fragment(display)
    # wait for it, unless it's what's shown already (then a pause, so the
    # program is back in its key wait)
    if frag and display != prev:
        print(f"u:{frag}:60000 w:{PAUSE} k:{key}")
    else:
        print(f"w:1200 k:{key}")
    prev = display
