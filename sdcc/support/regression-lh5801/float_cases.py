#!/usr/bin/env python3
"""float_cases.py - writes tests/floatops.c, the check of the port's float
library (device/lib/lh5801/_lh5801_fs.asm and the modules it lists)
against IEEE single precision, round to nearest even, as numpy does it.

Every case is bit patterns: a, b and the exact a+b, a-b, a*b, a/b; a and
sqrtf(a); integers and their floats. Random operands (fixed seed, so the
file only changes when this does) plus the edges rounding gets wrong:
ties, cancellation, carries out of the mantissa, shifts past the guard
bits. Exponents stay where no result is subnormal or infinite (the port
has neither, by design).

    python3 float_cases.py > tests/floatops.c
"""
import random
import numpy as np

f32 = np.float32
random.seed(1500)


def bits(x):
    return int(np.array(x, dtype=np.float32).view(np.uint32))


def fl(b):
    return np.array(b, dtype=np.uint32).view(np.float32)[()]


def rnd(lo=-30, hi=30):
    m = random.getrandbits(23)
    e = random.randint(lo, hi) + 127
    s = random.getrandbits(1)
    return fl((s << 31) | (e << 23) | m)


pairs = []
# edges
one = f32(1.0)
pairs += [
    (one, fl(0x33800000)),                      # 1 + 2^-24: a tie, stays 1
    (fl(0x3F800001), fl(0x33800000)),           # 1+ulp + half ulp: tie, to even (up)
    (fl(0x3F800001), fl(0xB3800000)),           # minus half ulp: tie, to even (down)
    (one, fl(0x33800001)),                      # just over half: up
    (fl(0x3FC00000), fl(0xBFC00000)),           # x + -x = +0
    (fl(0x3FFFFFFF), fl(0x34000000)),           # carry out of the mantissa
    (fl(0x3F7FFFFF), fl(0x33000000)),           # 0.99999994 + 2^-25
    (one, fl(0x30000000)),                      # 2^-31: below the guard byte, sticky
    (one, fl(0xB0000000)),                      # minus it: rounds back to 1
    (fl(0x4B7FFFFF), one),                      # 16777215 + 1
    (f32(3.0), f32(7.0)), (f32(1.0), f32(3.0)), (f32(2.0), f32(3.0)),
    (f32(10.0), f32(0.1)), (f32(-5.5), f32(2.25)), (f32(0.1), f32(0.2)),
    (f32(1e10), f32(1e-10)), (f32(123456.789), f32(-123456.78)),
    (f32(0.0), f32(4.5)), (f32(4.5), f32(0.0)), (f32(-0.0), f32(-2.0)),
    (fl(0x3F800000), fl(0x3F7FFFFF)),           # 1 - (1-ulp): exact, 2^-24
    (fl(0x40000000), fl(0x3FFFFFFF)),           # 2 - (2-ulp)
]
for _ in range(110):
    pairs.append((rnd(), rnd()))
for _ in range(25):                             # near each other: cancellation
    a = rnd(-5, 5)
    b = fl(bits(a) ^ 0x80000000)
    b = fl(bits(b) + random.randint(-300, 300))
    pairs.append((a, b))
for _ in range(25):                             # far apart: 20-35 bits of shift
    a = rnd(-5, 5)
    pairs.append((a, f32(a * f32(2.0) ** -random.randint(20, 35) * f32(random.uniform(1, 2)))))

roots = [f32(x) for x in (1.0, 2.0, 4.0, 0.25, 9.0, 1e-20, 3e20, 0.5, 1.5, 100.0)]
roots += [abs(rnd(-60, 60)) for _ in range(40)]

ints = [0, 1, -1, 255, 256, -128, 32767, -32768, 65535, 16777215, 16777216,
        16777217, 16777219, 33554435, 0x7FFFFFFF, -0x80000000, -16777217,
        123456789, -987654321]
ints += [random.getrandbits(32) - 2 ** 31 for _ in range(20)]
uints = [0xFFFFFFFF, 0x80000000, 0x80000080, 0x80000081, 3000000000]

tofix = [f32(x) for x in (0.0, -0.0, 0.5, -0.5, 0.9999, 1.0, -1.0, 1.5, -1.5, 255.9,
                         -129.0, 32767.5, 40000.0, -40000.0, 65536.0, 1e9, -1e9,
                         2147483520.0, -2147483648.0, 3e9, -3e9, 5e9, 1e30, -1e30)]


def sat(x, lo, hi):
    if np.isnan(x):
        return 0
    return int(max(lo, min(hi, np.trunc(np.float64(x)))))


def hx(v):
    return "0x%08lXUL" % (v & 0xFFFFFFFF)


out = []
w = out.append
w("/* GENERATED by float_cases.py -- the float library against IEEE single")
w("   precision, round to nearest even (numpy). Each check's number is")
w("   its group and case, shown with the value got. */")
w("#include <math.h>")
w("#include <errno.h>")
w("#include \"check.h\"")
w("")
w("typedef unsigned long u32;")
w("")
w("/* a, b, a+b, a-b, a*b, a/b */")
w("static const u32 bin[][6] = {")
for a, b in pairs:
    with np.errstate(all="ignore"):
        row = [bits(a), bits(b), bits(a + b), bits(a - b), bits(a * b), bits(a / b)]
    w("    {" + ", ".join(hx(v) for v in row) + "},")
w("};")
w("")
w("/* a, sqrtf(a) */")
w("static const u32 root[][2] = {")
for a in roots:
    w("    {%s, %s}," % (hx(bits(a)), hx(bits(np.sqrt(a)))))
w("};")
w("")
w("/* n, (float)n */")
w("static const long sint[][2] = {")
for n in ints:
    w("    {%dL, (long)%s}," % (n, hx(bits(f32(n)))) if n != -0x80000000 else
      "    {-2147483647L - 1, (long)%s}," % hx(bits(f32(n))))
w("};")
w("static const u32 uint[][2] = {")
for n in uints:
    w("    {%s, %s}," % (hx(n), hx(bits(f32(n)))))
w("};")
w("")
w("/* f, (long)f, (unsigned long)f, (int)f, (unsigned int)f, (signed char)f,")
w("   (unsigned char)f -- saturating, as the library does */")
w("static const u32 fix[][7] = {")
for f in tofix:
    neg = np.signbit(f) and f != 0
    row = [bits(f),
           sat(f, -2 ** 31, 2 ** 31 - 1),
           0 if f < 0 else sat(f, 0, 2 ** 32 - 1),
           sat(f, -32768, 32767),
           0 if f < 0 else sat(f, 0, 65535),
           sat(f, -128, 127),
           0 if f < 0 else sat(f, 0, 255)]
    w("    {" + ", ".join(hx(v) for v in row) + "},")
w("};")
w("")
w(r'''
#define N(t) (sizeof t / sizeof t[0])

union fu {
    float f;
    u32 u;
};

volatile union fu va, vb;
volatile long vl;
volatile unsigned long vul;

static void hex8(u32 v)
{
    unsigned char i;

    for (i = 0; i < 8; i++, v <<= 4) {
        unsigned char d = (unsigned char)(v >> 28);

        lcdPutChar(d < 10 ? '0' + d : 'A' + d - 10);
    }
}

/* FAIL g.ccc and the value got, in hex */
static void bad(unsigned char g, unsigned char c, u32 got)
{
    lcdClear();
    lcdPutString("FAIL ");
    lcdPutChar('0' + g);
    lcdPutChar('.');
    lcdPutChar('0' + c / 100);
    lcdPutChar('0' + c / 10 % 10);
    lcdPutChar('0' + c % 10);
    lcdPutChar(' ');
    hex8(got);
    stay();
}

static void want(unsigned char g, unsigned char c, u32 got, u32 w)
{
    if (got != w)
        bad(g, c, got);
}

int main(void)
{
    unsigned char i;
    union fu r;

    for (i = 0; i < N(bin); i++) {
        va.u = bin[i][0];
        vb.u = bin[i][1];
        r.f = va.f + vb.f;
        want(1, i, r.u, bin[i][2]);
        r.f = va.f - vb.f;
        want(2, i, r.u, bin[i][3]);
        r.f = va.f * vb.f;
        want(3, i, r.u, bin[i][4]);
        r.f = va.f / vb.f;
        want(4, i, r.u, bin[i][5]);
        {
            /* the comparisons, against the integer ordering of the values */
            float a = va.f, b = vb.f;
            unsigned char lt = (a < b), eq = (a == b), gt = (a > b);
            unsigned char wlt, weq;
            long sa = (long)bin[i][0], sb = (long)bin[i][1];

            if (sa < 0)
                sa = -2147483647L - 1 - sa;     /* order sign-magnitude as ints */
            if (sb < 0)
                sb = -2147483647L - 1 - sb;
            if (!(bin[i][0] & 0x7FFFFFFFUL) && !(bin[i][1] & 0x7FFFFFFFUL))
                sa = sb = 0;
            wlt = sa < sb;
            weq = sa == sb;
            want(5, i, (u32)lt << 16 | (u32)eq << 8 | gt, (u32)wlt << 16 | (u32)weq << 8 | (!wlt && !weq));
        }
    }
    for (i = 0; i < N(root); i++) {
        va.u = root[i][0];
        r.f = sqrtf(va.f);
        want(6, i, r.u, root[i][1]);
    }
    for (i = 0; i < N(sint); i++) {
        vl = sint[i][0];
        r.f = vl;
        want(7, i, r.u, (u32)sint[i][1]);
    }
    for (i = 0; i < N(uint); i++) {
        vul = uint[i][0];
        r.f = vul;
        want(8, i, r.u, uint[i][1]);
    }
    for (i = 0; i < N(fix); i++) {
        va.u = fix[i][0];
        want(9, i, (u32)(long)va.f, fix[i][1]);
        if (!(fix[i][0] & 0x80000000UL))      /* negative to unsigned: UB in C */
            want(9, i + 100, (unsigned long)va.f, fix[i][2]);
        want(9, i + 200, (u32)(int)va.f & 0xFFFF, fix[i][3] & 0xFFFF);
        if (!(fix[i][0] & 0x80000000UL))
            want(9, i + 100, (unsigned int)va.f, fix[i][4]);
        want(9, i + 200, (u32)(signed char)va.f & 0xFF, fix[i][5] & 0xFF);
        if (!(fix[i][0] & 0x80000000UL))
            want(9, i + 100, (unsigned char)va.f, fix[i][6]);
    }
    {
        /* small ints and chars to float */
        volatile int vi = -12345;
        volatile unsigned int vu = 54321u;
        volatile signed char vc = -100;
        volatile unsigned char vuc = 200;

        r.f = vi;
        want(10, 1, r.u, 0xC640E400UL);
        r.f = vu;
        want(10, 2, r.u, 0x47543100UL);
        r.f = vc;
        want(10, 3, r.u, 0xC2C80000UL);
        r.f = vuc;
        want(10, 4, r.u, 0x43480000UL);
    }
    va.f = -4.0f;
    errno = 0;
    r.f = sqrtf(va.f);
    want(11, 1, r.u, 0);
    want(11, 2, errno, EDOM);
    va.u = 0x80000000UL;
    r.f = sqrtf(va.f);
    want(11, 3, r.u, 0x80000000UL);
    /* x / 0 as SDCC's generic __fsdiv: an infinity of x's sign (not IEEE's
       sign rule), and 0 / 0 its NaN */
    va.f = 0.0f;
    vb.u = 0x80000000UL;
    r.f = va.f / vb.f;
    want(12, 1, r.u, 0xFFC00000UL);
    va.f = 3.0f;
    r.f = va.f / vb.f;
    want(12, 2, r.u, 0x7F800000UL);
    va.f = -3.0f;
    vb.f = 0.0f;
    r.f = va.f / vb.f;
    want(12, 3, r.u, 0xFF800000UL);
    pass();
    return 0;
}''')
print("\n".join(out))
